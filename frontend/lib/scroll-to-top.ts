/**
 * เด้งจอกลับขึ้นบนสุดทันทีหลังกดเปลี่ยนหน้าในตารางที่แบ่งหน้า
 *
 * ปุ่ม "ก่อนหน้า/ถัดไป" อยู่ท้ายตารางเสมอ ซึ่งแปลว่าตอนกดคนใช้อยู่ล่างสุดของหน้า
 * ถ้าไม่เลื่อนให้ พอข้อมูลหน้าใหม่ขึ้นมาจะเห็นแต่แถวท้าย ๆ กับหัวกลุ่มที่ค้างอยู่
 * ต้องลากขึ้นเองทุกครั้งกว่าจะเห็นว่าหน้านี้เริ่มที่ใคร
 *
 * ต้องเป็น "instant" ไม่ใช่ "auto" — globals.css ตั้ง html { scroll-behavior: smooth }
 * ไว้ทั้งเว็บ ส่วน "auto" แปลว่า "ตามที่ CSS บอก" ก็เลยกลับไปค่อย ๆ ไล่เลื่อนเหมือนเดิม
 * ตารางยาวหลายจอ ถ้าไล่เลื่อนคือรอทุกครั้งที่กดเปลี่ยนหน้า
 */
export function scrollPagerToTop() {
  if (typeof window === "undefined") return;

  window.scrollTo({ top: 0, behavior: "instant" });
}

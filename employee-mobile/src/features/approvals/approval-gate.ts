import type { ApprovalDetail, ApprovalItem } from './approvals';

/**
 * ใบนี้พร้อมให้กดอนุมัติหรือยัง
 *
 * ## ทำไมต้องมีด่านนี้
 *
 * คำร้องเอกสารเคยถูกตัดออกจากมือถือทั้งประเภท ด้วยเหตุผลว่าหัวหน้าจะกดอนุมัติ
 * โดยไม่ได้เปิดไฟล์อ่าน — ซึ่งเป็นความกังวลที่ถูกต้อง เพราะไฟล์แนบของใบขอ
 * เอกสารคือ **ตัวเอกสารที่กำลังจะรับรอง** ไม่ใช่หลักฐานประกอบ
 *
 * แต่การตัดทั้งประเภททิ้งไม่ได้แก้ปัญหา แค่ผลักไปให้เว็บ ทั้งที่หัวหน้าที่อยู่
 * นอกออฟฟิศก็ยังต้องอนุมัติอยู่ดี ด่านนี้จึงบังคับให้เปิดไฟล์ครบก่อนแทน
 *
 * ประเภทอื่นไม่บังคับ เพราะข้อมูลที่ใช้ตัดสิน (วันที่ จำนวนวัน เหตุผล) อยู่บน
 * การ์ดครบแล้ว ไฟล์แนบเป็นของประกอบ
 *
 * คืนข้อความเหตุผลแทน boolean เพราะจอต้องบอกผู้ใช้ด้วยว่าทำไมยังกดไม่ได้ —
 * ปุ่มที่กดไม่ติดโดยไม่มีคำอธิบายคือสิ่งที่ผู้ใช้อ่านว่าแอปพัง
 */
export function approvalBlockReason(params: {
  /** ใบที่กำลังจะกด */
  item: Pick<ApprovalItem, 'id' | 'type'>;
  /** ไฟล์ที่เปิดอ่านไปแล้วในเซสชันนี้ เป็น `<ใบ>:<ไฟล์>` */
  openedAttachments: ReadonlySet<string>;
  /** รายละเอียดของใบนี้ ถ้าผู้ใช้ยังไม่เคยเปิดแผ่นดูจะเป็น null */
  detail: Pick<ApprovalDetail, 'attachments'> | null;
}): string | null {
  if (params.item.type !== 'DOCUMENT') return null;

  /*
   * ยังไม่เคยเปิดแผ่นรายละเอียด = ยังไม่รู้ด้วยซ้ำว่ามีไฟล์อะไรบ้าง
   * ต้องกันไว้ ไม่งั้นจะกดอนุมัติจากหน้ารายการได้เลยโดยไม่เห็นอะไร
   */
  if (!params.detail) {
    return 'เปิดดูรายละเอียดและไฟล์แนบก่อนจึงจะอนุมัติได้';
  }

  const unread = params.detail.attachments.filter(
    (attachment) =>
      !params.openedAttachments.has(`${params.item.id}:${attachment.id}`),
  );

  if (unread.length === 0) return null;

  return `เปิดอ่านไฟล์แนบให้ครบก่อน (เหลืออีก ${unread.length} ไฟล์)`;
}

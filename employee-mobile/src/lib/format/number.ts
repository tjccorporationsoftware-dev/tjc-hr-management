/** ทศนิยมมากสุดที่แสดง — ละเอียดกว่านี้ไม่มีความหมายกับผู้ใช้ */
export const MAX_DECIMALS = 2;

export function formatNumber(value: number): string {
  if (!Number.isFinite(value)) return '0';
  /* จำนวนเต็มไม่ต้องผ่าน toFixed — กันเลขใหญ่ ๆ กลายเป็นรูปเลขยกกำลัง */
  if (Number.isInteger(value)) return String(value);

  return (
    value
      .toFixed(MAX_DECIMALS)
      /* ตัดศูนย์ท้ายทิ้ง ไม่ให้ 20 กลายเป็น "20.00" และ 9.5 เป็น "9.50" */
      .replace(/\.?0+$/, '')
      /* ปัดแล้วเหลือ "-0" อ่านแล้วสะดุด */
      .replace(/^-0$/, '0')
  );
}
